#!/usr/bin/env node
/* eslint-disable */
/**
 * Generates react/utils/currencyFractionDigitsTable.ts from the runtime's own
 * ICU/CLDR data.
 *
 * It probes every three-letter code (AAA..ZZZ) through Intl.NumberFormat and
 * keeps only the ones whose default fraction digits differ from 2, which is
 * what ICU uses for every other code, known or unknown. The app then applies
 * "exceptions table, else 2", which reproduces ICU exactly for any code without
 * depending on Intl.supportedValuesOf (that list omits codes ICU still knows,
 * such as CLF, UYI and UYW).
 *
 * IMPORTANT: run it on a CLDR 47 runtime, which is the snapshot we commit
 * (Node 24.13.0, ICU 77.1):
 *
 *   ~/.asdf/installs/nodejs/24.13.0/bin/node scripts/generate-currency-fraction-digits.js \
 *     > react/utils/currencyFractionDigitsTable.ts
 *
 * The output must match the committed file. Running it on a different CLDR
 * version (e.g. CLDR 48, where COP/HUF/IDR/PKR became 0 digits and RSD became
 * 2) produces a different table on purpose: do not commit that output unless
 * the change is a deliberate decision.
 */
const DEFAULT_DIGITS = 2
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
const exceptions = []

for (const a of LETTERS) {
  for (const b of LETTERS) {
    for (const c of LETTERS) {
      const code = a + b + c
      const digits = new Intl.NumberFormat('en', {
        style: 'currency',
        currency: code,
      }).resolvedOptions().maximumFractionDigits

      if (digits !== DEFAULT_DIGITS) {
        exceptions.push(`  ${code}: ${digits},`)
      }
    }
  }
}

const cldr = process.versions.cldr || 'unknown'

process.stdout.write(
  [
    '/**',
    ' * Generated by scripts/generate-currency-fraction-digits.js from',
    ` * Node ${process.version} / ICU ${process.versions.icu} / CLDR ${cldr}.`,
    ' *',
    ` * Default fraction digits per ISO 4217 code. Only the ${exceptions.length} codes`,
    ` * that differ from ${DEFAULT_DIGITS} are listed; every other code, known or unknown,`,
    ` * uses ${DEFAULT_DIGITS}, exactly as ICU does.`,
    ' *',
    ' * Regenerate on a CLDR 47 runtime (Node 24.13.0):',
    ' *   node scripts/generate-currency-fraction-digits.js > react/utils/currencyFractionDigitsTable.ts',
    ' */',
    `export const DEFAULT_CURRENCY_FRACTION_DIGITS = ${DEFAULT_DIGITS}`,
    '',
    'export const CURRENCY_FRACTION_DIGITS_EXCEPTIONS: Record<string, number> = {',
    ...exceptions,
    '}',
    '',
  ].join('\n')
)
